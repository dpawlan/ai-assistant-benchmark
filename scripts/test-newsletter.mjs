import assert from 'node:assert/strict';
import { cleanIssueHtml, parseIssues, isMondayMorning } from '../src/lib/newsletter-feed.ts';
import fs from 'node:fs';
const dirty = '<script>alert(1)</script><img src="https://example.com/x.png" onerror="evil()"><a href="javascript:evil()">bad</a><iframe src="https://example.com"></iframe><p style="position:fixed">Good</p>';
const clean = cleanIssueHtml(dirty);
assert(!/script|onerror|javascript:|iframe|position:fixed/.test(clean));
assert(clean.includes('https://example.com/x.png'));
assert(clean.includes('Good'));
assert.throws(()=>parseIssues('<invalid>'));
const xml = '<rss><channel><item><title>A &amp; B</title><link>https://assistant-benchmark-newsletter.beehiiv.com/p/test</link><pubDate>Mon, 09 Nov 2026 15:03:25 GMT</pubDate><content:encoded><![CDATA[<p>Issue body</p>]]></content:encoded></item></channel></rss>';
assert.equal(parseIssues(xml)[0].title, 'A & B');
assert.equal(parseIssues(xml)[0].slug, 'test');
assert.throws(()=>parseIssues(xml.replace('https://assistant-benchmark-newsletter.beehiiv.com','https://evil.com')));
assert.equal(isMondayMorning(new Date('2026-11-09T10:59:00Z')), false);
assert.equal(isMondayMorning(new Date('2026-11-09T11:00:00Z')), true);
assert.equal(isMondayMorning(new Date('2026-11-09T16:59:00Z')), true);
assert.equal(isMondayMorning(new Date('2026-11-09T17:00:00Z')), false);
assert.equal(isMondayMorning(new Date('2026-11-10T14:00:00Z')), false);
assert.equal(isMondayMorning(new Date('2026-07-06T10:00:00Z')), true);
assert.equal(isMondayMorning(new Date('2026-07-06T16:00:00Z')), false);
const saved = JSON.parse(fs.readFileSync('data/newsletter-snapshot.json','utf8'));
assert.equal(saved.length, 5);
assert(saved.every(issue=>cleanIssueHtml(issue.html).length>1000));
console.log('Newsletter: feed parsing, content safety, saved archive and Eastern refresh window passed.');
